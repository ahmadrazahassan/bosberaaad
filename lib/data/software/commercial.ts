function plan(
  name: string,
  price: number | null,
  vat: boolean | null,
  description: string,
  options: Partial<PricingPlan> = {},
): PricingPlan {
  return {
    name,
    price,
    period: "month",
    vat_inclusive: vat,
    description,
    features: [],
    ...options,
  };
}

